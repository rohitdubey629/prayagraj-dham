async function seed() {
  await connectDB();

  // WARNING: this wipes the entire shlokas collection before reseeding.
  // Only safe to run against an empty/dev database.
  await Shloka.deleteMany({});

  const submittedByName = "Admin";
  const submittedByEmail = process.env.ADMIN_EMAIL || "admin@example.com";

  const docs = shlokas.map((shloka) => ({
    text: shloka.text,
    source: shloka.source,
    meaning: shloka.meaning,
    submittedByName,
    submittedByEmail,
    status: "approved" as const,
    featured: Boolean(shloka.featured),
    reviewedAt: new Date(),
  }));

  await Shloka.insertMany(docs);

  console.log(`Seeded ${docs.length} shlokas as approved (${docs.filter((d) => d.featured).length} featured).`);

  await mongoose.disconnect();
  process.exit(0);
}

seed().catch((error) => {
  console.error("Seeding failed:", error);
  process.exit(1);
});
